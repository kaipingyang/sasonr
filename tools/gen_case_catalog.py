"""Write the case catalogues of the verification matrices (Markdown).

    python -I tools/gen_case_catalog.py RESULTS.csv OUT_DIR

RESULTS.csv is the per-case output of tools/run_conformance.R for the areas
fn_matrix/ and fmt_matrix/ (and optionally the function pilot functions/).
Writes OUT_DIR/cases_functions.md and OUT_DIR/cases_formats.md: one section
per function / format with a table of its cases (case id, what it tests,
the SAS 9.4 result, whether sasonr agrees, tags).  The cases themselves are
local assets (tests/conformance/ is not in git); the catalogue is refreshed
after every regression run.
"""
import csv
import os
import re
import sys
import datetime

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(os.path.dirname(HERE), "tests", "conformance")


def classify(r):
    st = r["status"]
    if st in ("pass", "both_error"):
        return "pass"
    if st == "unsupported":
        return "unsupported"
    if st == "fail":
        fl = r["failed_layers"]
        if fl == "log":
            return "log"
        tol = r.get("tol", "")
        if tol not in ("", "NA") and not re.search("attr|log", fl):
            return "approximate"
    return "mismatch"


MARK = {"pass": "✅", "approximate": "≈ last bits differ (not a pass)", "log": "value ✅ / log NOTE differs",
        "unsupported": "unsupported (fails loud)", "mismatch": "❌"}


def header_desc(prog):
    try:
        first = open(prog, encoding="latin-1").readline()
    except OSError:
        return "", []
    m = re.match(r"/\*\s*\S+?:\s*(.*)$", first.strip())
    desc = m.group(1) if m else first.strip()
    tags = []
    for ln in open(prog, encoding="latin-1").read(2000).splitlines():
        if ln.strip().startswith("tags:"):
            tags = [t.strip(" */") for t in ln.split(":", 1)[1].split(",") if t.strip(" */")]
    return desc, tags


def sas_result(case_dir):
    exp = os.path.join(case_dir, "expected")
    res = os.path.join(exp, "files", "results.txt")
    out = ""
    if os.path.exists(res):
        txt = open(res, encoding="latin-1").read()
        e = re.search(r"err=(\d+)", txt)
        b = re.search(r"best=\s*(\S*)", txt)
        q = re.search(r"^@@Q \S+ (.*)$", txt, re.M)
        m = re.search(r"^@@M \S+ \[(.*)\]$", txt, re.M)
        v = re.search(r"vlen=(\d+)", txt)
        if b:
            out = b.group(1)
        elif q:
            out = q.group(1)[:40] + ("…" if len(q.group(1)) > 40 else "")
        if v:
            out += " (length %s)" % v.group(1)
        if e and e.group(1) != "0":
            out += ", _ERROR_=1"
    put = os.path.join(exp, "put.txt")
    if not out and os.path.exists(put):
        m = re.search(r"^@@M \S+ \[(.*)\]$", open(put, encoding="latin-1").read(), re.M)
        if m:
            out = "%SYSFUNC: " + m.group(1)[:40]
    notes = os.path.join(exp, "log_notes.txt")
    if os.path.exists(notes):
        t = open(notes, encoding="latin-1").read()
        if re.search(r"^ERROR", t, re.M):
            out = (out + "; " if out else "") + "ERROR"
        elif "Invalid argument" in t:
            out += "; NOTE invalid argument"
        elif "Missing values were generated" in t:
            out += "; NOTE missing values"
        elif "Mathematical operations" in t:
            out += "; NOTE math. operations"
    return out.replace("|", "\\|")


def write(area, title, rows, out_path):
    by = {}
    for r in rows:
        if not r["case"].startswith(area + "/"):
            continue
        feat = r["case"].split("/")[1]
        by.setdefault(feat, []).append(r)
    lines = ["# %s" % title, "",
             "> Generated by `tools/gen_case_catalog.py` on %s from the offline regression results (do not edit)."
             % datetime.date.today().isoformat(),
             "> Cases are local (`tests/conformance/%s/`); the SAS 9.4 results come from `tools/refresh_gold.py`." % area,
             "", "Legend: ✅ agrees with SAS 9.4 bit for bit (values, length, `_ERROR_`, log NOTEs, PUT output);"
             " ≈ only the last bits of a number differ (not a pass); unsupported = sasonr stops with"
             " `sasonr_unsupported`; ❌ differs.", ""]
    total = {}
    for feat in sorted(by):
        for r in by[feat]:
            c = classify(r)
            total[c] = total.get(c, 0) + 1
    lines.append("Total: %d cases — %s." % (sum(total.values()), ", ".join("%s %d" % (k, v) for k, v in sorted(total.items()))))
    lines.append("")
    for feat in sorted(by):
        rs = sorted(by[feat], key=lambda r: r["case"])
        cls = [classify(r) for r in rs]
        status = "verified" if all(c == "pass" for c in cls) else ("mismatch" if "mismatch" in cls else
                                                                     ("approximate" if "approximate" in cls else "partial"))
        lines += ["## %s" % feat, "",
                  "Bit-identical: %d / %d cases, status: **%s**" % (cls.count("pass"), len(rs), status), "",
                  "| Case | Tests | SAS 9.4 result | sasonr | Tags |", "|---|---|---|---|---|"]
        for r, c in zip(rs, cls):
            d = os.path.join(ROOT, r["case"])
            desc, tags = header_desc(os.path.join(d, "program.sas"))
            desc = desc.replace("|", "\\|")
            tags = [t for t in tags if t not in ("fn_matrix", "fmt_matrix", feat.lower())]
            lines.append("| %s | %s | %s | %s | %s |" % (r["case"].split("/")[-1], desc, sas_result(d), MARK[c],
                                                         ", ".join(tags)))
        lines.append("")
    open(out_path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return len(by)


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    rows = list(csv.DictReader(open(argv[0], encoding="utf-8")))
    os.makedirs(argv[1], exist_ok=True)
    n1 = write("fn_matrix", "Function verification cases", rows, os.path.join(argv[1], "cases_functions.md"))
    n2 = write("fmt_matrix", "Format and informat verification cases", rows, os.path.join(argv[1], "cases_formats.md"))
    print("functions: %d sections, formats: %d sections" % (n1, n2))


if __name__ == "__main__":
    main(sys.argv[1:])
