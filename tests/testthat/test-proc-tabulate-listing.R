# PROC TABULATE listing: the printed tables of complete steps, line by line.

# The statistics of PROC TABULATE have no rows in the statistics registry yet,
# so the runs use sasonr.strict = FALSE (the registry warnings are muffled).
tab_run <- function(prog) {
  withr::local_options(sasonr.strict = FALSE)
  withCallingHandlers(sas_run(prog), sasonr_strict_warning = function(w) invokeRestart("muffleWarning"))
}
tab_listing <- function(prog) tab_run(prog)$listing

test_that("a two-dimensional table: frame, row-title area, heading rows and rules", {
  prog <- r"---(
options nocenter nodate nonumber formdlim=' ' pagesize=max linesize=132;
proc format;
  value trtf 1 = 'Low' 2 = 'High';
run;
data have;
  length grp $1 sub $1;
  input grp $ sub $ trt v w;
  datalines;
a x 1 10 1.5
a x 2 20 2.5
a y 1 30 3.5
b x 2 40 4.5
b y 1 50 .
b y 2 60 6.5
c x 1 . 7.5
c y 2 80 8.5
. y 1 90 9.5
;
run;

proc tabulate data=have;
  class grp;
  var v;
  table grp, v*mean;
run;
)---"
  expect_identical(tab_listing(prog), c(
    "----------------------------------------------",
    "|                               |     v      |",
    "|                               |------------|",
    "|                               |    Mean    |",
    "|-------------------------------+------------|",
    "|grp                            |            |",
