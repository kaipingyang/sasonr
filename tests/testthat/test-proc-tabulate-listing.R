test_that("a table without a statistic keyword runs in strict mode", {
  prog <- "data a; input g $ h $; datalines;\nx p\ny q\n;\nrun;\nproc tabulate data=a; class g h; table g, h; run;"
  withr::local_options(sasonr.strict = TRUE)
  r <- sas_run(prog)
  expect_identical(r$listing[c(1, length(r$listing))], rep(strrep("-", 59), 2))
  expect_s3_class(r$ods[[1]], "sas_ods_table")
  expect_identical(attr(r$ods[[1]], "name"), "Table")
})

test_that("CLASS / MISSING applies to the variables of its own CLASS statement", {
  data <- paste(
    "data m; length grp $1 sub $1; input grp $ sub $ v; datalines;",
    "a x 1", "a y 2", "b x 3", ". y 4", "b . 5", ";", "run;", sep = "\n")
  run <- function(cls) tab_run(paste0(data, "\nproc tabulate data=m; ", cls, " var v; table grp, sub*v*n; run;"))$ods[[1]]
  levels_of <- function(t) {
    hd <- attr(t, "header")
    list(rows = t$grp, cols = unlist(hd$text[hd$role == "class"]))
  }
  expect_identical(levels_of(run("class grp sub;")), list(rows = c("a", "b"), cols = c("x", "y")))
  expect_identical(levels_of(run("class grp sub / missing;")), list(rows = c(" ", "a", "b"), cols = c("", "x", "y")))
  expect_identical(levels_of(run("class grp; class sub / missing;")), list(rows = c("a", "b"), cols = c("", "x", "y")))
  expect_identical(levels_of(run("class grp / missing; class sub;")), list(rows = c(" ", "a", "b"), cols = c("x", "y")))
  t <- run("class grp; class sub / missing;")
  expect_identical(unname(as.matrix(t[-1])), matrix(c(NA, 1, 1, 1, 1, NA), 2L))
})

test_that("headings wrap at word boundaries and cut a long word with a hyphen", {
  fail <- function(what) stop(what)
  expect_identical(tab_wrap("A very long label for the analysis variable", 6L, fail, cut = TRUE),
                   c("A very", "long", "label", "for", "the", "analy-", "sis", "varia-", "ble"))
  expect_identical(tab_wrap("A long box text that must wrap in the row title area", 31L, fail, cut = FALSE),
                   c("A long box text that must wrap", "in the row title area"))
  expect_error(tab_wrap(strrep("x", 32), 31L, fail, cut = FALSE))
})

