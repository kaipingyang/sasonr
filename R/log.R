# The log of a submission, kept as events.
#
# Code that writes to the log reports an event (log_emit()); the plain text
# of the log is rendered from the events (log_text()).  The events of a
# submission are kept by its engine (`eng$events`, run.R) and appended to the
# session's events when the submission ends (log_flush()).
#
# Only the R/log*.R files assign the log stores: the engine's events, step
# index (`step_no`), program (`program`, `src_line`), the session's events and
# programs (`log_programs`), the approximate features of a submission
# (`rt$approx`) and the step buffer `.log` of the evaluation environment of a
# step (generated code appends PUT lines and the PDV dump to it; the engine
# moves it into the events when the step ends).  tests/testthat/test-architecture.R
# checks that rule.
#
# One event is a list:
#   seq     arrival order within the submission
#   step    index of the step (0: open code: global statements and macro
#           statements outside a step)
#   phase   global, compile, run, step_end, step_close or submission
#   kind    note, warning, error, put (PUT / %PUT output) or echo
#   id      catalogue id (log_catalog.R); "raw" for text written as it is
#   args    named values of the template
#   at      c(line, column) of a single place, or NULL
#   places  places of a merged message (data frame line, col, count), or NULL
#   text    the plain lines, rendered when the event is emitted (LINESIZE and
#           NOTES are those in effect then)
#   src     the last program line read when the event was written (the source
#           echo of the rich views, log_items())
#
# The engine also keeps what the source echo needs (log_program()): the
# program lines, the steps (index, label, first line) and the lines at which
# OPTIONS SOURCE / NOSOURCE take effect.

log_kinds <- c("note", "warning", "error", "put", "echo")
log_phases <- c("global", "compile", "run", "step_end", "step_close", "submission")

# A new engine has no events; `step_count` counts its steps, `step_no` is the
# step being run (0: open code).
log_engine_init <- function(eng) {
  eng$events <- list()
  eng$step_count <- 0L
  eng$step_no <- 0L
  eng$src_line <- 0L
  eng$program <- list(lines = character(), steps = data.frame(step = integer(), label = character(), line = integer(),
                                                                   tail_from = integer(), tail_to = integer()),
                      source = data.frame(line = integer(), on = logical()),
                      ls = data.frame(line = integer(), ls = integer()), skip = integer())
  invisible(eng)
}

# The program of a submission (its lines as written, numbered from 1) and
# the LINESIZE and SOURCE / NOSOURCE in effect when it starts.
log_program <- function(eng, text) {
  o <- eng$session$options
  eng$program$lines <- strsplit(text, "\n", fixed = TRUE)[[1]] %||% character()
  eng$program$ls <- data.frame(line = 0L, ls = vctrs::vec_cast(o$linesize %||% 132L, integer()))
  eng$program$source <- data.frame(line = 0L, on = !isFALSE(o$source))
  eng$program$echo_omit <- NULL
  invisible()
}

# Internal check: SOURCE / LINESIZE settings are recorded in line order (text
# that a macro generates takes effect at the line of the invocation, the
# macro processor's sink counts no lines in it).
log_setting_order_check <- function(lines, line) {
  if (length(lines) && !is.na(line) && line < max(lines)) {
    rlang::abort(paste0("a SOURCE / LINESIZE setting at line ", line, " after one at line ", max(lines), "."),
                 .internal = TRUE)
  }
  invisible()
}

# Whether program line `line` is macro-affected: the macro processor
# resolved, called or removed something on it (a macro variable reference,
# a macro call or statement, a macro comment, also with an empty result;
# mp_consumed()), in the submission being run (rt$macro_lines).
log_macro_line <- function(line, rt = rt_diag()) {
  length(line) == 1L && !is.na(line) && line %in% rt$macro_lines
}

# A NOTE place (`at`: c(line, column)) on a macro-affected line: its column
# (and line) are not those of SAS, which counts the text there differently;
# it fails loud.
log_place_check <- function(at) {
  if (length(at) >= 1L && !is.na(at[1]) && log_macro_line(vctrs::vec_cast(at[1], integer()))) {
    abort_unsupported_construct("a NOTE place on a line with macro references (its line and column)", vctrs::vec_cast(at[1], integer()))
  }
  invisible()
}

# The source echo of the current submission is left out (`reason`): the
# plain log keeps the messages and the PUT output (log_items()).
log_echo_omit <- function(eng, reason) {
  if (is.null(eng$program$echo_omit)) eng$program$echo_omit <- reason
  invisible()
}

# OPTIONS SOURCE / NOSOURCE followed by more text on its line: in the program
# (`options nosource; data a;`) the echo splits the line; generated by a macro
# or a macro variable (it takes effect after the line of the invocation) with
# more text on that line (`%m data a; x = 1; run;`) the blank line before what
# the steps on that line write differs.  Neither is implemented: the echo of the
# submission is left out.  A comment after the statement is no text here.
log_setting_line_check <- function(eng, line) {
  l <- eng$program$lines[line]
  if (length(l) != 1L || is.na(l)) return(invisible())
  low <- tolower(l)
  at <- gregexpr("(^|[^a-z0-9_])options?[^a-z0-9_]", low)[[1]]
  more <- if (at[1] < 0L && log_macro_line(line, eng$session$rt)) {
    !grepl("^\\s*([%&][a-z_][a-z0-9_]*\\.?(\\(.*\\))?\\s*;?)\\s*$", low)
  } else {
    rest <- if (at[1] < 0L) low else substr(low, at[length(at)], nchar(low))
    semi <- regexpr(";", rest, fixed = TRUE)
    after <- gsub("/\\*.*?\\*/", "", substr(rest, semi + 1L, nchar(rest)), perl = TRUE)
    semi > 0L && nzchar(trimws(after))
  }
  if (more) log_echo_omit(eng, "OPTIONS SOURCE or NOSOURCE followed by more text on its line")
  invisible()
}

# OPTIONS LINESIZE= in the statement that ends at `line` (the echo of later
# lines wraps at it).
log_source_ls <- function(eng, line, ls) {
  log_setting_order_check(eng$program$ls$line, line)
  eng$program$ls <- vctrs::vec_rbind(eng$program$ls, data.frame(line = as.integer(line), ls = as.integer(ls)))
  invisible()
}

# Program lines that are not echoed (the data lines after DATALINES / CARDS).
log_source_skip <- function(eng, lines) {
  eng$program$skip <- union(eng$program$skip, vctrs::vec_cast(lines, integer()))
  invisible()
}

# The end of the program lines of a DATA or PROC step: the source echo writes
# a blank line before what the step writes when it runs (log_step_close());
# once per step and chunk of program text until more program lines are read.
log_boundary <- function(eng) {
  key <- c(eng$step_no %||% 0L, eng$src_line %||% 0L, eng$chunk_no %||% 0L)
  if (identical(eng$boundary_at, key)) return(invisible())
  eng$boundary_at <- key
  log_emit(eng, "echo", text = "", phase = "step_end")
}

# A step starts: its index and label, and the program has been read up to
# `last`.  `tail`: the lines of the step echoed after what it writes when it
# runs (the `;` and RUN; lines after the data lines of a DATALINES step: they
# stay in the step's group of the HTML view), c(from, to) or NULL.
log_step_start <- function(eng, label, line, last, tail = NULL) {
  eng$step_count <- eng$step_count + 1L
  eng$step_no <- eng$step_count
  st <- eng$program$steps
  tail <- vctrs::vec_cast(tail %||% c(NA, NA), integer())
  eng$program$steps <- vctrs::vec_rbind(st, data.frame(step = eng$step_no, label = label, line = as.integer(line),
                                            tail_from = tail[1], tail_to = tail[2]))
  log_source_read(eng, last)
}

# A chunk of program text without a step up to line `last`: when it is only
# RUN; or `;` (the RUN; that ends a DATALINES step; comments allowed) and
# nothing else was read after the step's lines, its lines stay in that step
# (log_step_start(), `tail`).  TRUE when they do.
log_step_tail_extend <- function(eng, last, text) {
  bare <- gsub("(?s)/\\*.*?\\*/", " ", text, perl = TRUE)
  if (!grepl("^(\\s*(run\\s*)?;)+\\s*$", bare, ignore.case = TRUE, perl = TRUE)) return(FALSE)
  st <- eng$program$steps
  k <- nrow(st)
  if (!k || is.na(st$tail_from[k]) || st$step[k] != eng$step_count || length(last) != 1L || is.na(last) ||
      eng$src_line > st$tail_to[k]) return(FALSE)
  # the program lines between the step's lines and this chunk (a macro
  # statement such as %PUT does not move src_line) hold only blanks and comments
  first <- vctrs::vec_cast(last, integer()) - lengths(regmatches(text, gregexpr("\n", text, fixed = TRUE)))
  if (first - 1L > st$tail_to[k]) {
    gap <- paste(eng$program$lines[(st$tail_to[k] + 1L):(first - 1L)], collapse = "\n")
    if (grepl("\\S", gsub("(?s)/\\*.*?\\*/", " ", gap, perl = TRUE), perl = TRUE)) return(FALSE)
  }
  eng$program$steps$tail_to[k] <- max(st$tail_to[k], vctrs::vec_cast(last, integer()))
  TRUE
}

# The program has been read up to line `last`.
log_source_read <- function(eng, last) {
  if (length(last) == 1L && !is.na(last)) eng$src_line <- max(eng$src_line, vctrs::vec_cast(last, integer()))
  invisible()
}

# The open code between steps (global statements, macro statements).
log_open_code <- function(eng) {
  eng$step_no <- 0L
  invisible()
}

# OPTIONS SOURCE / NOSOURCE in the statement that ends at `line`: the lines
# after it are echoed or not (the setting is kept in the session options).
log_source_option <- function(eng, line, on) {
  log_setting_line_check(eng, line)
  log_setting_order_check(eng$program$source$line, line)
  eng$program$source <- vctrs::vec_rbind(eng$program$source, data.frame(line = as.integer(line), on = on))
  eng$session$options$source <- on
  invisible()
}

# A new session: no events.
log_session_init <- function(s) {
  s$events <- list()
  s$log_programs <- list()
  invisible(s)
}

# The phase of an event emitted while the engine is in `eng$phase`.
log_phase_of <- function(eng) {
  switch(eng$phase %||% "global",
    compile = "compile",
    sql = , execute = , execute_data = "run",
    "global"
  )
}

# Record one event.  `text`: the plain lines (an element may hold several
# lines separated by "\n"; `split = FALSE`: the lines as given, blank ones
# included); a catalogued message (`id`, log_catalog.R) is rendered from its
# template and the arguments in `...` when no text is given.  An event
# without text is not recorded.
log_emit <- function(eng, kind = NULL, id = "raw", ..., text = NULL, at = NULL, places = NULL, phase = NULL, src = NULL,
                     split = TRUE) {
  if (!identical(id, "raw")) {
    m <- log_entry(id)
    kind <- kind %||% m$kind
    if (is.null(text)) text <- log_render(id, list(...))
  }
  if (is.null(kind) || !kind %in% log_kinds) rlang::abort(paste0("log_emit(): unknown kind `", kind %||% "NULL", "`."), .internal = TRUE)
  # (an empty element of a message is dropped, as in the text log; an "echo"
  # event is the blank line of the source echo)
  lines <- if (identical(kind, "echo")) "" else if (!split) as.character(text) else if (length(text)) {
    log_split_lines(text, put = rep(identical(kind, "put"), length(text)))$lines
  }
  if (!length(lines)) return(invisible())
  phase <- phase %||% log_phase_of(eng)
  if (!phase %in% log_phases) rlang::abort(paste0("log_emit(): unknown phase `", phase, "`."), .internal = TRUE)
  ev <- list(seq = length(eng$events) + 1L, step = eng$step_no %||% 0L, phase = phase, kind = kind, id = id,
             args = list(...), at = at, places = places, text = lines, src = vctrs::vec_cast(src %||% eng$src_line %||% 0L, integer()))
  eng$events[[ev$seq]] <- ev
  invisible()
}

# The kind of a log line written as text: a message line starts a NOTE,
# WARNING or ERROR; a line indented by 6 that follows a message line
# continues it; any other line is PUT output (PUT lines, the PDV dump).
# `put`: lines known to be PUT output whatever they start with.
log_line_kinds <- function(lines, put = rep(FALSE, length(lines))) {
  kinds <- character(length(lines))
  prev <- "put"
  for (k in seq_along(lines)) {
    l <- lines[k]
    kinds[k] <- if (put[k]) "put" else if (startsWith(l, "NOTE")) "note" else if (startsWith(l, "WARNING")) "warning" else
      if (startsWith(l, "ERROR")) "error" else if (prev != "put" && startsWith(l, "      ")) prev else "put"
    prev <- kinds[k]
  }
  kinds
}

# Lines as the text log shows them: each element split at "\n".  An element
# of PUT output (`put`) is always written: an empty element is an empty line
# and a trailing "\n" ends with an empty line (a PUT line whose values are
# blank).  An empty element of a message is no line (an empty line inside an
# element is kept).  No element is NA (an internal error).
log_split_lines <- function(x, put = rep(FALSE, length(x))) {
  x <- as.character(x)
  if (anyNA(x)) rlang::abort("log_split_lines(): an NA log line.", .internal = TRUE)
  x[put] <- paste0(x[put], "\n")
  parts <- strsplit(x, "\n", fixed = TRUE)
  list(lines = unlist(parts) %||% character(), put = rep(put, lengths(parts)))
}

# Record lines of mixed kinds (the step buffer `.log`, the NOTEs of a PROC
# DATASETS step): one event per message or PUT line, in order.  `put`: the
# elements known to be PUT output whatever they start with (only the step
# buffer knows them, log_emit_buffer()); the kind of the other lines comes
# from their text (log_line_kinds()).
log_emit_lines <- function(eng, lines, phase = NULL, put = rep(FALSE, length(lines))) {
  if (!length(lines)) return(invisible())
  sp <- log_split_lines(lines, put)
  lines <- sp$lines
  if (!length(lines)) return(invisible())
  kinds <- log_line_kinds(lines, sp$put)
  start <- c(TRUE, kinds[-1] == "put" | kinds[-1] != kinds[-length(kinds)] |
                     !startsWith(lines[-1], "      "))
  grp <- cumsum(start)
  for (g in unique(grp)) log_emit(eng, kinds[grp == g][1], text = lines[grp == g], phase = phase, split = FALSE)
  invisible()
}

# The plain text of a list of events (messages and PUT output, without the
# source echo): one element per log line.
log_text <- function(events) {
  unlist(lapply(events, function(ev) if (!identical(ev$kind, "echo")) ev$text)) %||% character()
}

# Whether the log views (`$log` of a result, sas_log()) show the source echo
# unless told otherwise.
log_echo_default <- TRUE

# End of a submission: its events go to the session (also after an R error).
log_flush <- function(eng) {
  s <- eng$session
  sub <- length(s$log_programs) + 1L
  s$events <- c(s$events, lapply(eng$events, function(ev) c(ev, list(sub = sub))))
  s$log_programs[[sub]] <- eng$program
  invisible()
}

# The log callbacks of a submission: macro-time WARNINGs (only with
# sasonr.step_notes), ERRORs, NOTEs and %PUT lines.
# Macro-time events follow the line the macro processor has reached.
log_bind_callbacks <- function(eng, rt, ses) {
  src <- function() max(ses$line %||% 0L, eng$src_line %||% 0L)
  rt$on_warn <- if (eng$step_notes) function(msg) log_emit(eng, "warning", text = paste("WARNING:", msg), src = src())
  rt$on_error <- function(msg) log_emit(eng, "error", text = paste("ERROR:", msg), src = src())
  rt$on_note <- function(msg) log_emit(eng, "note", text = msg, src = src())
  ses$on_put <- function(line) {
    log_emit(eng, "put", text = line, src = src())
    script_record_put(eng, ses, line, src())
  }
  invisible()
}

# The approximate features used in a submission (strict_gate(), registry.R):
# reset when it starts; log_approx_add() is TRUE for a feature not yet used.
log_approx_reset <- function(rt) {
  rt$approx <- character()
  invisible()
}

log_approx_add <- function(rt, feature) {
  if (feature %in% rt$approx) return(FALSE)
  rt$approx <- c(rt$approx, feature)
  TRUE
}

# End of a submission run with sasonr.strict = FALSE: one NOTE listing the
# approximate features used (strict_gate(), registry.R).  Written once, also
# when an R error stops the submission (sas_run() calls it on exit).
log_approx_close <- function(eng) {
  if (isTRUE(eng$approx_closed)) return(invisible())
  eng$approx_closed <- TRUE
  feats <- eng$session$rt$approx
  if (!length(feats)) return(invisible())
  # the LINESIZE of the submission (sas_run() may have unbound the session)
  text <- log_render("sasonr.approximate", list(features = paste(feats, collapse = ", ")),
                     ls = eng$session$options$linesize %||% 132L)
  log_emit(eng, id = "sasonr.approximate", features = paste(feats, collapse = ", "), text = text, phase = "submission")
  invisible()
}

# A %PUT line in the log (mp_put_stmt() fails loud on an empty text).
log_macro_put <- function(ses, line) {
  if (!length(line) || !all(nzchar(line))) rlang::abort("log_macro_put(): an empty %PUT line.", .internal = TRUE)
  if (is.function(ses$on_put)) ses$on_put(line)
  invisible()
}

# The step buffer `.log` of the evaluation environment of a step.
log_buffer_init <- function(env) {
  env$.log <- character()
  invisible(env)
}

# Messages (NOTEs, data errors) added by the engine are named "msg"; the
# lines generated code appends (PUT output, the PDV dump) are unnamed.
log_buffer_add <- function(env, lines) {
  if (length(lines)) env$.log <- c(env$.log, stats::setNames(as.character(lines), rep("msg", length(lines))))
  invisible()
}

# The step buffer as events: its lines not named "msg" are PUT output (a
# buffer without names holds PUT output only).
log_emit_buffer <- function(eng, buf, phase = "run") {
  if (!length(buf)) return(invisible())
  nm <- names(buf)
  put <- if (is.null(nm)) rep(TRUE, length(buf)) else is.na(nm) | nm != "msg"
  log_emit_lines(eng, unname(buf), phase = phase, put = put)
}

# Catalogued messages ----------------------------------------------------------

# The catalogue entry of `id`.
log_entry <- function(id) {
  m <- log_catalog[[id]]
  if (is.null(m)) rlang::abort(paste0("log message `", id, "` is not in the catalogue."), .internal = TRUE)
  m
}

# The template lines of a message with `<name>` replaced by `args$name`.
log_fill <- function(lines, args, id) {
  m <- gregexpr("<[a-z_]+>", lines)
  regmatches(lines, m) <- lapply(regmatches(lines, m), function(keys) {
    vapply(keys, function(k) {
      v <- args[[substr(k, 2L, nchar(k) - 1L)]]
      if (length(v) != 1L) {
        rlang::abort(paste0("log message `", id, "`: argument ", k, " must be one value."), .internal = TRUE)
      }
      if (is.numeric(v)) sprintf("%d", as.integer(v)) else as.character(v)
    }, "", USE.NAMES = FALSE)
  })
  lines
}

# The plain lines of message `id` (without its places) at LINESIZE `ls`.
log_render <- function(id, args = list(), ls = rt_linesize()) {
  m <- log_entry(id)
  lines <- log_fill(m$template, args, id)
  switch(m$wrap,
    none = lines,
    fixed = if (nchar(lines[1]) <= ls) lines else c(m$wrapped, lines[-1]),
    linesize = log_wrap(paste(lines, collapse = " "), ls = ls),
    join = {
      one <- paste(trimws(lines, "left"), collapse = " ")
      # the fit is judged on the documented text, which names the system
      # with a word three characters shorter than "sasonr"
      w <- nchar(one)
      if (isTRUE(m$neutral)) w <- w - 3L * lengths(regmatches(one, gregexpr("\\bsasonr\\b", one)))
      if (w <= ls) one else lines
    },
    rlang::abort(paste0("log message `", id, "`: unknown wrap rule `", m$wrap, "`."), .internal = TRUE)
  )
}

# Places of merged messages ------------------------------------------------------

# The diagnostic state that keeps the places of `m` for the current step.
log_place_state <- function(m) if (identical(m$store, "compile")) ct_diag() else rt_diag()

# Add a place to the merged message `id` of the current step: a conversion
# place, a missing value generated (`n` times), a mathematical operation that
# could not be performed.  `at`: c(line, column).
log_place <- function(id, line = NULL, col = NULL, n = 1L, at = c(line, col)) {
  log_place_check(at)
  m <- log_entry(id)
  if (identical(m$places, "none")) rlang::abort(paste0("log message `", id, "` has no places."), .internal = TRUE)
  st <- log_place_state(m)
  key <- if (identical(m$key, "line_col")) sprintf("%d:%d", as.integer(line), as.integer(col %||% 0L)) else at_key(at)
  v <- st$places[[id]]
  if (identical(m$places, "counted")) {
    v[key] <- (if (key %in% names(v)) v[[key]] else 0L) + vctrs::vec_cast(n, integer())
  } else {
    v <- c(v, key)
  }
  st$places[[id]] <- v
  invisible()
}

# The places of `id` kept in the state `st` (NULL: none).
log_places_get <- function(st, id) st$places[[id]]

# Save, restore and reset the places of a state (an evaluation whose records
# are dropped: a WHERE condition, %SYSFUNC, a PROC SQL expression).
log_places_save <- function(st) st$places
log_places_restore <- function(st, saved) {
  st$places <- saved
  invisible()
}
log_places_reset <- function(st, init = list()) {
  st$places <- init
  invisible()
}

# The places in their written order.
log_order_places <- function(keys, rule) {
  switch(rule,
    line_col = sorted_places(keys),
    line_coltext = {
      ln <- as.integer(sub(":.*$", "", keys))
      keys[order(ln, sub("^.*:", "", keys), method = "radix")]
    },
    rlang::abort(paste0("unknown place order `", rule, "`."), .internal = TRUE)
  )
}

# The lines of message `id` with its places: `keys` "line:col" (list) or the
# counts named by "line:col" (counted).
log_place_lines <- function(id, keys) {
  m <- log_entry(id)
  entries <- if (identical(m$places, "counted")) {
    k <- log_order_places(names(keys), m$order)
    sprintf("%d at %s", as.integer(keys[k]), k)
  } else {
    k <- log_order_places(unique(keys), m$order)
    if (m$pad > 0L) sprintf(paste0("%-", m$pad, "s"), k) else k
  }
  c(log_render(id), place_lines(entries))
}

# The places as a data frame (line, col, count).
log_places_frame <- function(id, keys) {
  counted <- identical(log_entry(id)$places, "counted")
  k <- if (counted) names(keys) else unique(keys)
  p <- strsplit(k, ":", fixed = TRUE)
  part <- function(i) suppressWarnings(as.integer(vapply(p, function(x) x[i], "")))
  data.frame(line = part(1L), col = part(2L), count = if (counted) as.integer(keys) else rep(1L, length(k)))
}

# One event for the merged message `id` with the places `keys`.
log_emit_places <- function(eng, id, keys, phase = NULL) {
  if (!length(keys)) return(invisible())
  log_emit(eng, id = id, text = log_place_lines(id, keys), places = log_places_frame(id, keys), phase = phase)
}

# End of a step ------------------------------------------------------------------

# The log of the end of a step of kind `kind` (log_close_order): the
# compile-time NOTEs of the translation `tr`, what the step wrote while it
# ran (`env$.log`), the NOTEs from the run-time counters, the observations
# read, the procedure's NOTEs and the output data sets (`stopped`: the step
# was stopped, "may be incomplete").  `notes`: NOTES in effect.
log_step_close <- function(eng, kind, tr = NULL, env = NULL, stopped = FALSE, notes = TRUE) {
  ord <- log_close_order[[kind]]
  if (is.null(ord)) rlang::abort(paste0("log_step_close(): unknown kind of step `", kind, "`."), .internal = TRUE)
  rt <- rt_diag()
  for (k in seq_len(nrow(ord))) {
    if (ord$notes[k] && !notes) next
    part <- ord$part[k]
    switch(part,
      compile = log_emit_lines(eng, tr$compile_notes, phase = "compile"),
      run = {
        log_boundary(eng)
        log_emit_buffer(eng, env$.log)
      },
      input.new_line = if (isTRUE(rt$flow_note)) log_emit(eng, id = "input.new_line", phase = "step_end"),
      mv.generated = ,
      math.failed = log_emit_places(eng, part, log_places_get(rt, part), phase = "step_end"),
      ods = for (o in rt$ods_notes) log_emit(eng, id = "ds.created", name = o$name, nobs = o$nobs, nvar = o$nvar, phase = "step_end"),
      ods.warn = for (nm in rt$ods_missing) log_emit_lines(eng, ods_not_created_lines(nm), phase = "step_end"),
      looping = if (isTRUE(rt$looping)) log_emit(eng, id = "ds.looping", phase = "step_end"),
      reads = log_emit_reads(eng, tr),
      proc = log_emit_lines(eng, rt$proc_notes, phase = "step_end"),
      datasets = log_emit_datasets(eng, tr$outputs, stopped),
      rlang::abort(paste0("log_step_close(): unknown part `", part, "`."), .internal = TRUE)
    )
  }
  invisible()
}

# The observations read from each input data set.  PROC SORT reports no
# observations read from an empty data set; PROC PRINT reports an empty one
# as "No observations".  A MERGE with repeats of BY values in more than one
# data set says so first.
log_emit_reads <- function(eng, tr) {
  rt <- rt_diag()
  if (isTRUE(rt$merge_repeats)) {
    # a STOP statement before or inside the repeated BY group leaves the NOTE
    # out; a STOP after it is not known, so any STOP fails loud
    if (isTRUE(rt$stop_stmt)) abort_unsupported("MERGE with repeats of BY values in a step that ran a STOP statement")
    log_emit(eng, id = "ds.merge_repeats", phase = "step_end")
  }
  if (identical(tr$reasons, "PROC SORT")) rt$reads <- Filter(function(r) r$n > 0, rt$reads)
  print <- identical(tr$reasons, "PROC PRINT")
  for (r in rt$reads) {
    nm <- toupper(r$name)
    if (print && r$n == 0) {
      log_emit(eng, id = "ds.no_obs", name = nm, phase = "step_end")
    } else if (print && identical(r$nvar, 0L)) {
      log_emit(eng, id = "ds.no_vars", name = nm, phase = "step_end")
    } else if (is.null(r$where)) {
      log_emit(eng, id = "ds.read", nobs = r$n, name = nm, phase = "step_end")
    } else {
      log_emit(eng, id = "ds.read_where", nobs = r$n, name = nm, where = r$where, phase = "step_end")
    }
  }
  invisible()
}

# The size of each output data set ("may be incomplete" when the step was stopped).
log_emit_datasets <- function(eng, outputs, stopped = FALSE) {
  for (nm in outputs) {
    d <- get0(nm, envir = eng$session$work, inherits = FALSE)
    if (is.null(d)) next
    log_emit(eng, id = if (stopped) "ds.incomplete" else "ds.created", name = toupper(nm), nobs = nrow(d),
             nvar = ncol(d), phase = "step_close")
  }
  invisible()
}
