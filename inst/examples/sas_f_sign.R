# SIGN: each call is explained above it and followed by its result

# A negative number has sign -1.
sas_f_sign(-3)  # sign(-3) = -1

# Zero has sign 0.
sas_f_sign(0)  # sign(0) = 0

# A positive number has sign 1.
sas_f_sign(2.5)  # sign(2.5) = 1

# A missing argument gives a missing result.
sas_f_sign(NA_real_)  # sign(.) = .
