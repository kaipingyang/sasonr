# REVERSE: each call is explained above it and followed by its result

# REVERSE reverses the order of the characters.
sas_f_reverse("abc")  # reverse('abc') = "cba"

# Trailing blanks become leading blanks.
sas_f_reverse("abc  ")  # reverse('abc  ') = "  cba"

# A blank string stays blank.
sas_f_reverse(" ")  # reverse('') = ""
